"""Studio-independent tests. Run: python3 -m unittest test_writeback (from this directory).

The schema and the fingerprint vector come from the checked-in evidence, which
was generated by a real Studio run (see README.md).
"""
import json
import os
import sqlite3
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import writeback

HERE = Path(__file__).resolve().parent
EVIDENCE = HERE / "evidence"
FILE_ID = "file-1"
STAMP = "2026-01-02T03:04:05.678Z"
NEW = "<p>new caf\u00e9</p>"
OLD = "<p>old \u201ctext\u201d</p>"


class WritebackTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name).resolve()
        (self.root / writeback.MARKER).write_text("test\n")
        self.db = self.root / "db.sqlite"
        con = sqlite3.connect(self.db)
        con.executescript((EVIDENCE / "schema.sql").read_text())
        self.data = {
            "id": FILE_ID, "project": "p1", "folder": None, "name": "Note", "type": "text",
            "content": OLD, "createdAt": "2026-01-01T00:00:00.000Z",
            "updatedAt": "2026-01-01T00:00:00.000Z",
            "contentUpdatedAt": "2026-01-01T00:00:00.000Z",
            "isTrashed": False, "position": 0,
        }
        self.insert(con, FILE_ID, "text", 0, self.data)
        con.execute(
            "INSERT INTO outbox (user_id, kind, entity_type, entity_id, method, url, body,"
            " temp_ids, status, attempts, created_at, updated_at)"
            " VALUES ('local','file.update','file',?,'PUT','/files/x/','{}','[]','pending',0,'t','t')",
            (FILE_ID,),
        )
        con.commit()
        con.close()

    def insert(self, con, fid, ftype, trashed, data):
        con.execute(
            "INSERT INTO files (id, user_id, project_id, folder_id, type, is_trashed,"
            " position, created_at, data, mirrored_at) VALUES (?,?,?,?,?,?,?,?,?,?)",
            (fid, "local", "p1", None, ftype, trashed, 0, data["createdAt"], json.dumps(data), 1),
        )

    def query(self, sql, *args):
        con = sqlite3.connect(self.db)
        try:
            return con.execute(sql, args).fetchall()
        finally:
            con.close()

    def run_writeback(self, file_id=FILE_ID, html=NEW):
        return writeback.apply_text_writeback(self.db, self.root, file_id, html, now=STAMP)

    def test_updates_only_content_and_content_timestamps(self):
        self.run_writeback()
        data, mirrored = self.query("SELECT data, mirrored_at FROM files WHERE id=?", FILE_ID)[0]
        expected = dict(self.data, content=NEW, updatedAt=STAMP, contentUpdatedAt=STAMP)
        self.assertEqual(json.loads(data), expected)
        self.assertEqual(mirrored, writeback._epoch_ms(STAMP))

    def test_leaves_indexed_columns_and_outbox_alone(self):
        columns = "user_id, project_id, folder_id, type, is_trashed, position, created_at"
        before = self.query(f"SELECT {columns} FROM files"), self.query("SELECT * FROM outbox")
        self.run_writeback()
        self.assertEqual(before, (self.query(f"SELECT {columns} FROM files"), self.query("SELECT * FROM outbox")))

    def test_records_pre_image_in_studio_shape(self):
        result = self.run_writeback()
        row = self.query(
            "SELECT id, content, extras, fingerprint, reason, file_name, content_size, created_at"
            " FROM local_versions"
        )[0]
        encoded = json.dumps(OLD, ensure_ascii=False, separators=(",", ":"))
        self.assertEqual(row, (
            result["pre_image_version_id"], encoded, None, writeback.fingerprint(OLD),
            "manual", "Note", len(encoded), STAMP,
        ))

    def test_skips_pre_image_when_latest_version_matches(self):
        con = sqlite3.connect(self.db)
        con.execute(
            "INSERT INTO local_versions (id, file_id, content, fingerprint, reason, content_size, created_at)"
            " VALUES ('existing', ?, ?, ?, 'manual', 1, '2025-01-01T00:00:00.000Z')",
            (FILE_ID, json.dumps(OLD), writeback.fingerprint(OLD)),
        )
        con.commit()
        con.close()
        self.assertIsNone(self.run_writeback()["pre_image_version_id"])
        self.assertEqual(self.query("SELECT id FROM local_versions"), [("existing",)])

    def test_empty_content_has_no_pre_image(self):
        con = sqlite3.connect(self.db)
        self.insert(con, "empty", "text", 0, dict(self.data, id="empty", content=""))
        con.commit()
        con.close()
        self.assertIsNone(self.run_writeback(file_id="empty")["pre_image_version_id"])

    def test_caps_history_at_studio_limit_dropping_oldest(self):
        con = sqlite3.connect(self.db)
        for i in range(writeback.MAX_VERSIONS_PER_FILE):
            con.execute(
                "INSERT INTO local_versions (id, file_id, content, fingerprint, reason, content_size, created_at)"
                " VALUES (?,?,?,?,?,?,?)",
                (f"v{i:02d}", FILE_ID, '"x"', f"fp{i}", "manual", 3, f"2025-01-01T00:00:{i:02d}.000Z"),
            )
        con.commit()
        con.close()
        self.run_writeback()
        ids = [r[0] for r in self.query("SELECT id FROM local_versions")]
        self.assertEqual(len(ids), writeback.MAX_VERSIONS_PER_FILE)
        self.assertNotIn("v00", ids)

    def assert_refused_and_unchanged(self, **kwargs):
        before = self.query("SELECT data FROM files"), self.query("SELECT COUNT(*) FROM local_versions")
        with self.assertRaises(writeback.Refused):
            writeback.apply_text_writeback(**kwargs)
        self.assertEqual(before, (self.query("SELECT data FROM files"), self.query("SELECT COUNT(*) FROM local_versions")))

    def test_refuses_missing_trashed_and_non_text_files(self):
        con = sqlite3.connect(self.db)
        self.insert(con, "trash", "text", 1, dict(self.data, id="trash"))
        self.insert(con, "grid", "grid", 0, dict(self.data, id="grid", type="grid"))
        con.commit()
        con.close()
        for fid in ("missing", "trash", "grid"):
            self.assert_refused_and_unchanged(
                db_path=self.db, disposable_root=self.root, file_id=fid, new_html=NEW
            )

    def test_refuses_library_without_marker(self):
        (self.root / writeback.MARKER).unlink()
        self.assert_refused_and_unchanged(
            db_path=self.db, disposable_root=self.root, file_id=FILE_ID, new_html=NEW
        )

    def test_refuses_database_outside_disposable_root(self):
        with tempfile.TemporaryDirectory() as other:
            (Path(other) / writeback.MARKER).write_text("x")
            with self.assertRaises(writeback.Refused):
                writeback.assert_disposable(self.db, other)

    def test_refuses_live_library_path_even_when_marked(self):
        home = self.root / "home"
        db = home / ".config/studio-desktop/byokwa/db.sqlite"
        db.parent.mkdir(parents=True)
        (home / writeback.MARKER).write_text("x")
        env = {k: v for k, v in os.environ.items() if k != "XDG_CONFIG_HOME"}
        with mock.patch.dict(os.environ, dict(env, HOME=str(home)), clear=True):
            with self.assertRaises(writeback.Refused):
                writeback.assert_disposable(db, home)

    def test_fingerprint_matches_value_computed_by_real_studio(self):
        seed = json.loads((EVIDENCE / "report.json").read_text())["seed"]
        self.assertEqual(
            writeback.fingerprint(seed["studio_snapshot"]["content"]),
            seed["studio_snapshot_fingerprint"],
        )

    def test_timestamp_format_matches_javascript(self):
        self.assertRegex(writeback.iso_now(), r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d{3}Z$")


if __name__ == "__main__":
    unittest.main()
